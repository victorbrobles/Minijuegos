// Segundo bingo de cada grupo. Para que no haya errores, las listas NO se escriben a mano: cada futbolista se
// describe una vez con sus etiquetas y cada categoría reúne a todos los que llevan su etiqueta. Así un futbolista
// que sale encaja en todas las categorías que cumple (y solo en esas).
// Todas las categorías son hechos cerrados y con fecha («hasta 2025»), para que no cambien con el tiempo.

function construir(id, grupo, titulo, categorias, futbolistas) {
  const lista = categorias.map(([cid, nombre, etiqueta]) => ({
    id: cid,
    nombre,
    jugadores: Object.entries(futbolistas).filter(([, tags]) => tags.includes(etiqueta)).map(([n]) => n)
  }));
  return { id, grupo, titulo, categorias: lista };
}

